function setupAutocomplete(inputId) {
    var input = document.getElementById(inputId);

    // create suggestion box dynamically
    var suggestionBox = document.createElement("div");
    suggestionBox.setAttribute("class", "autocomplete-results");
    suggestionBox.setAttribute("data-highlight", "1"); // added
    input.parentNode.appendChild(suggestionBox);

    input.addEventListener("keyup", function () {
        var value = this.value.toLowerCase();
        suggestionBox.innerHTML = "";

        if (!value) return;

        var filtered = stations.filter(function (item) {
            return item.toLowerCase().includes(value);
        });

        filtered.slice(0, 10).forEach(function (item, index) {
            // match format: "Name (City, ST), CODE"
            var parts = item.match(/^(.*) \((.*), (.*)\), (.*)$/);
            if (!parts) return;

            var displayName = parts[1]; // Name
            var city = parts[2];        // City
            var state = parts[3];       // State
            var code = parts[4];        // Code

            var resultDiv = document.createElement("div");
            resultDiv.setAttribute("class", "autocomplete-result");
            resultDiv.setAttribute("data-index", index);

            resultDiv.innerHTML = item;

            resultDiv.onclick = function () {
                input.value = item; // original full string
                suggestionBox.innerHTML = "";
            };

            suggestionBox.appendChild(resultDiv);
        });
    });

    // hide on click outside
    document.addEventListener("click", function (e) {
        if (!input.contains(e.target)) {
            suggestionBox.innerHTML = "";
        }
    });
}

